-- Run this once in the Supabase SQL editor.
create table if not exists public.click_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  event_name text not null check (char_length(event_name) between 1 and 80),
  target text not null check (char_length(target) between 1 and 30),
  path text not null check (char_length(path) between 1 and 300),
  session_id text not null check (char_length(session_id) between 1 and 80),
  actor_id text check (actor_id is null or char_length(actor_id) between 1 and 100),
  metadata jsonb not null default '{}'::jsonb,
  user_agent text
);

alter table public.click_events enable row level security;

revoke all on table public.click_events from anon, authenticated;
revoke all on sequence public.click_events_id_seq from anon, authenticated;

create index if not exists click_events_created_at_idx
  on public.click_events (created_at desc);
create index if not exists click_events_event_name_idx
  on public.click_events (event_name, created_at desc);
create index if not exists click_events_actor_id_idx
  on public.click_events (actor_id, created_at desc)
  where actor_id is not null;
